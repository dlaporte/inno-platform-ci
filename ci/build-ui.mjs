#!/usr/bin/env node
// A function app's browser interface (APP-CONTRACT §1.1, "Browser
// interface"). Tenant CI's app-build job runs it between the symlink guard
// and the bundle, so the interface is built from the same audited tree, in
// the same job with no credential, as the Worker that serves it.
//
// Usage: node ci/build-ui.mjs --tools <dir> [--app <dir>]
//
// --tools is the platform's build tools install (the mirror's ci/build/,
// installed under $RUNNER_TEMP): this script runs ITS esbuild and Tailwind
// CLI, never a copy the author's lockfile could name. --app defaults to app.
//
// What it does, in order:
//   1. Removes a committed <app>/.ui-build/, with a warning: the directory is
//      this script's output, so only what CI builds reaches the Worker, as a
//      committed app/node_modules is removed before the install.
//   2. No <app>/ui/: prints that there is nothing to build and exits 0, so
//      every app without an interface builds exactly as before.
//   3. Bundles <app>/ui/main.{tsx,ts,jsx,js} for the browser (one ES module,
//      minified, the automatic JSX runtime), resolving packages from
//      <app>/node_modules, the tree the dependency gate audited. Images and
//      fonts the interface imports are inlined as data URLs; CSS it imports
//      is collected into one stylesheet.
//   4. <app>/ui/styles.css, when present, leads the stylesheet: through the
//      Tailwind CLI when it imports "tailwindcss" (scanning <app>/ui/ for
//      class names), else through esbuild.
//   5. Writes <app>/.ui-build/ui.ts, a generated module the author's
//      app/index.ts imports: UI_SCRIPT and UI_STYLES (the built text) and
//      UI_SCRIPT_PATH and UI_STYLES_PATH (/ui.<hash>.js and .css, content
//      hashed, so the Worker may serve them immutable). The bundle step that
//      follows bundles it like any other module, so the interface counts
//      toward the 16 MiB cap.
//
// Exit 0 when built or when there is nothing to build; 1, with annotations,
// when the build fails; 2, with the usage, on a bad argument.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { annotate, annotateAll, isMainModule, logSafe } from "./cli.mjs";

const USAGE = "Usage: node ci/build-ui.mjs --tools <dir> [--app <dir>]";

export const UI_DIR = "ui";
export const OUT_DIR = ".ui-build";
export const ENTRIES = ["main.tsx", "main.ts", "main.jsx", "main.js"];
export const STYLES = "styles.css";

// Imported files esbuild inlines as data URLs. Anything else that is not
// code or CSS fails the build with esbuild's "No loader is configured".
export const ASSET_LOADERS = Object.fromEntries(
  [".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".svg", ".ico", ".woff", ".woff2", ".ttf", ".otf"].map((ext) => [ext, "dataurl"]),
);

/** True when the stylesheet imports Tailwind (v4's single entry). */
export function importsTailwind(css) {
  return /@import\s+(?:url\(\s*)?["']tailwindcss["']/.test(css);
}

/** The first 16 hex digits of the text's sha256. */
export function contentHash(text) {
  return createHash("sha256").update(text).digest("hex").slice(0, 16);
}

/** The generated module's source: four string constants, JSON-escaped. */
export function generatedModule({ script, styles }) {
  return [
    "// Generated by the platform's CI (ci/build-ui.mjs) from app/ui/. Do not edit or commit it:",
    "// CI removes a committed copy and builds it again.",
    `export const UI_SCRIPT_PATH = ${JSON.stringify(`/ui.${contentHash(script)}.js`)};`,
    `export const UI_STYLES_PATH = ${JSON.stringify(`/ui.${contentHash(styles)}.css`)};`,
    `export const UI_SCRIPT = ${JSON.stringify(script)};`,
    `export const UI_STYLES = ${JSON.stringify(styles)};`,
    "",
  ].join("\n");
}

function fail(title, what, fix, file) {
  annotate({ title, what, fix, file });
  return 1;
}

/**
 * Builds the interface. Returns the exit code; annotations go to stderr.
 *
 * @param {{ tools: string, app?: string, log?: (s: string) => void }} opts
 */
export async function buildUi({ tools, app = "app", log = (s) => console.log(s) }) {
  const out = join(app, OUT_DIR);
  let committed = false;
  try { lstatSync(out); committed = true; } catch { /* absent */ }
  if (committed) {
    annotate({
      level: "warning",
      title: "Committed build output removed",
      what: `${out} is the platform's build output, so CI removed the committed copy before building`,
      fix: `add ${out}/ to .gitignore and remove it from the repository (git rm -r --cached ${out})`,
      file: out,
    });
    rmSync(out, { recursive: true, force: true });
  }

  const uiDir = join(app, UI_DIR);
  if (!existsSync(uiDir)) {
    log(`No ${uiDir}/; no browser interface to build.`);
    return 0;
  }
  const entry = ENTRIES.map((e) => join(uiDir, e)).find((p) => existsSync(p));
  if (!entry) {
    return fail("Browser interface entry missing", `${uiDir}/ has no entry module`,
      `add ${uiDir}/main.tsx (or main.ts, main.jsx, main.js), or remove ${uiDir}/`, uiDir);
  }

  const esbuild = await import(pathToFileURL(join(tools, "node_modules", "esbuild", "lib", "main.js")).href);
  const common = {
    bundle: true,
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    loader: ASSET_LOADERS,
    logLevel: "silent",
    write: false,
    outdir: "/ui-out",
    define: { "process.env.NODE_ENV": '"production"' },
  };

  const errorsOf = (err) => (err && Array.isArray(err.errors) ? err.errors : [{ text: String(err?.message ?? err) }]);
  const report = (err) => {
    const items = errorsOf(err).map((e) => (e.location ? { what: e.text, file: e.location.file, line: e.location.line } : { what: e.text }));
    annotateAll({
      title: "Browser interface build",
      fix: "fix the import or the code it names; a package the interface imports belongs under dependencies in app/package.json",
      items,
    });
    for (const i of items) console.error(logSafe(i.file ? `${i.file}:${i.line}: ${i.what}` : i.what, 600));
    return 1;
  };

  let script = "";
  let imported = "";
  try {
    const r = await esbuild.build({ ...common, entryPoints: { ui: entry }, format: "esm", jsx: "automatic" });
    for (const f of r.outputFiles) {
      if (f.path.endsWith(".js")) script = f.text;
      else if (f.path.endsWith(".css")) imported = f.text;
    }
  } catch (err) {
    return report(err);
  }

  let lead = "";
  const stylesPath = join(uiDir, STYLES);
  if (existsSync(stylesPath)) {
    const css = readFileSync(stylesPath, "utf8");
    if (importsTailwind(css)) {
      const tmp = mkdtempSync(join(tmpdir(), "ui-css-"));
      const outCss = join(tmp, "styles.css");
      const r = spawnSync(join(tools, "node_modules", ".bin", "tailwindcss"),
        ["--input", relative(uiDir, stylesPath), "--output", outCss, "--minify"],
        { cwd: uiDir, encoding: "utf8", env: { ...process.env, NODE_PATH: join(tools, "node_modules") } });
      if (r.status !== 0) {
        console.error(logSafe(r.stderr || r.stdout || "", 2000));
        rmSync(tmp, { recursive: true, force: true });
        return fail("Tailwind build", `the Tailwind CLI could not build ${stylesPath}; its reason ends the step log`,
          "fix the stylesheet; the platform supplies tailwindcss itself, so app/package.json need not declare it", stylesPath);
      }
      lead = readFileSync(outCss, "utf8");
      rmSync(tmp, { recursive: true, force: true });
    } else {
      try {
        const r = await esbuild.build({ ...common, entryPoints: { styles: stylesPath } });
        lead = r.outputFiles.map((f) => f.text).join("");
      } catch (err) {
        return report(err);
      }
    }
  }

  const styles = [lead, imported].filter(Boolean).join("\n");
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "ui.ts"), generatedModule({ script, styles }));
  log(`Built ${out}/ui.ts from ${entry}: script ${script.length} bytes, styles ${styles.length} bytes.`);
  return 0;
}

if (isMainModule(import.meta.url)) {
  let values;
  try {
    ({ values } = parseArgs({ args: process.argv.slice(2), options: { tools: { type: "string" }, app: { type: "string", default: "app" } } }));
    if (!values.tools) throw new Error("--tools is required");
  } catch (err) {
    console.error(`${logSafe(err.message)}\n${USAGE}`);
    process.exit(2);
  }
  process.exit(await buildUi({ tools: values.tools, app: values.app }));
}
